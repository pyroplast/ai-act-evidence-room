"""Events, signed webhooks and the optional email digest.

Events
    After every scan, inside the same transaction that records it, ``queue_events``
    turns the scan's rows in ``v_regressions`` into ``finding.regressed`` /
    ``finding.resolved`` events, or a failed scan into one ``scan.failed`` event. Each
    event is appended to the audit chain (``event.emitted``) and queued as one delivery
    per subscribed webhook. Queuing in the recording transaction is an outbox: a scan cannot be
    recorded without its events, and an event cannot exist for a scan that rolled back.

Webhooks
    The body is the event payload as canonical JSON (sorted keys, no whitespace,
    UTF-8). It is signed as

        X-Evidence-Signature: t=<unix seconds>,v1=<hex hmac_sha256(secret, "<t>.<body>")>

    A delivery succeeds on any 2xx. Otherwise it is retried 1, 5, 30 and 120 minutes
    after each failed attempt, then given up. Every attempt is its own row in
    ``deliveries`` (D-019). ``deliver_due`` claims due attempts with
    ``FOR UPDATE SKIP LOCKED``, so several workers never send the same attempt twice.

Email
    If SMTP_HOST and DIGEST_TO are set, the worker emails one plain-text digest per scan
    that produced events. Off by default.

No text here is generated by a model, and none of it is a legal conclusion: events
repeat the scanner's own rule, status and basis, and every payload carries the scope
line.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import logging
import smtplib
import urllib.error
import urllib.request
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from datetime import datetime, timedelta
from email.message import EmailMessage
from typing import Any

from sqlalchemy import select, text
from sqlalchemy.orm import Session, sessionmaker

from evidence_room import SCOPE_LINE, __version__, audit
from evidence_room.config import Settings
from evidence_room.models import Delivery, Webhook

log = logging.getLogger("evidence_room.notify")

ACTOR = "system:notifier"
EVENTS = ("finding.regressed", "finding.resolved", "scan.failed")
RETRY_DELAYS = (
    timedelta(minutes=1),
    timedelta(minutes=5),
    timedelta(minutes=30),
    timedelta(minutes=120),
)
MAX_ATTEMPTS = 1 + len(RETRY_DELAYS)
SIGNATURE_HEADER = "X-Evidence-Signature"
SEND_TIMEOUT_SECONDS = 10.0

Clock = Callable[[], datetime]
# (url, body, headers) -> (HTTP status or None, error text or None)
Sender = Callable[[str, bytes, dict[str, str]], tuple[int | None, str | None]]


@dataclass(frozen=True)
class Event:
    name: str
    event_id: str
    entity: str  # "finding" or "scan"
    entity_id: int
    payload: dict[str, Any]


# --- signing -------------------------------------------------------------------------


def canonical_body(payload: dict[str, Any]) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode(
        "utf-8"
    )


def sign(secret: str, timestamp: int, body: bytes) -> str:
    mac = hmac.new(secret.encode("utf-8"), f"{timestamp}.".encode() + body, hashlib.sha256)
    return f"t={timestamp},v1={mac.hexdigest()}"


def verify(
    secret: str, header: str, body: bytes, *, now: int | None = None, tolerance: int | None = 300
) -> tuple[bool, str]:
    """Check a signature header. Receivers can copy this function (docker/webhook-sink)."""
    try:
        parts = dict(item.split("=", 1) for item in header.split(","))
        timestamp = int(parts["t"])
        given = parts["v1"]
    except (KeyError, ValueError):
        return False, "malformed signature header"
    expected = sign(secret, timestamp, body).split("v1=", 1)[1]
    if not hmac.compare_digest(expected, given):
        return False, "signature mismatch"
    if tolerance is not None and now is not None and abs(now - timestamp) > tolerance:
        return False, "timestamp outside tolerance"
    return True, "ok"


# --- building events -----------------------------------------------------------------


def _event_id(name: str, scan_id: int, fingerprint: str = "") -> str:
    return hashlib.sha256(f"{name}\x1f{scan_id}\x1f{fingerprint}".encode()).hexdigest()


def _scan_context(session: Session, scan_id: int) -> dict[str, Any]:
    row = session.execute(
        text(
            """
            SELECT s.id, s.status, s.error, s.finished_at, s.touchpoint_id,
                   t.kind, t.target, t.matter_id, m.title AS matter_title,
                   c.name AS client_name
            FROM scans s
            JOIN touchpoints t ON t.id = s.touchpoint_id
            JOIN matters m     ON m.id = t.matter_id
            JOIN clients c     ON c.id = m.client_id
            WHERE s.id = :id
            """
        ),
        {"id": scan_id},
    ).one()
    return dict(row._mapping)


def _artifacts(session: Session, scan_id: int) -> list[dict[str, Any]]:
    rows = session.execute(
        text("SELECT kind, name, sha256 FROM artifacts WHERE scan_id = :s ORDER BY id"),
        {"s": scan_id},
    )
    return [dict(r._mapping) for r in rows]


def _evidence_for(kind: str, target: str, artifacts: list[dict[str, Any]]) -> dict[str, Any]:
    """The stored file a finding was computed from, plus the scan's report.json."""
    report = next((a["sha256"] for a in artifacts if a["kind"] == "report_json"), None)
    source = None
    if kind == "page":
        source = next((a for a in artifacts if a["kind"] == "html"), None)
    else:
        path = target.split("#", 1)[0]
        source = next((a for a in artifacts if a["name"] == path), None)
    return {
        "sha256": source["sha256"] if source else None,
        "kind": source["kind"] if source else None,
        "name": source["name"] if source else None,
        "report_sha256": report,
    }


def _base(ctx: dict[str, Any], name: str, event_id: str, occurred_at: datetime) -> dict[str, Any]:
    return {
        "event": name,
        "event_id": event_id,
        "occurred_at": audit.format_at(occurred_at),
        "source": f"ai-act-evidence-room {__version__}",
        "scope": SCOPE_LINE,
        "matter": {
            "id": ctx["matter_id"],
            "title": ctx["matter_title"],
            "client": ctx["client_name"],
        },
        "touchpoint": {"id": ctx["touchpoint_id"], "kind": ctx["kind"], "target": ctx["target"]},
    }


def events_for_scan(
    session: Session, scan_id: int, *, base_url: str, occurred_at: datetime
) -> list[Event]:
    ctx = _scan_context(session, scan_id)
    artifacts = _artifacts(session, scan_id)

    if ctx["status"] == "error":
        event_id = _event_id("scan.failed", scan_id)
        payload = _base(ctx, "scan.failed", event_id, occurred_at)
        payload["scan"] = {
            "id": scan_id,
            "finished_at": audit.format_at(ctx["finished_at"]) if ctx["finished_at"] else None,
            "error": ctx["error"],
        }
        payload["evidence"] = _evidence_for(ctx["kind"], ctx["target"], artifacts)
        payload["link"] = f"{base_url}/scans/{scan_id}"
        return [Event("scan.failed", event_id, "scan", scan_id, payload)]

    if ctx["status"] != "done":
        return []

    rows = session.execute(
        text(
            """
            SELECT r.*, f.detail, f.target, f.location, f.basis
            FROM v_regressions r
            JOIN findings f ON f.id = COALESCE(r.finding_id, r.prev_finding_id)
            WHERE r.scan_id = :s
            ORDER BY r.change, r.rule_id, r.fingerprint
            """
        ),
        {"s": scan_id},
    ).mappings()
    events: list[Event] = []
    for r in rows:
        name = "finding.regressed" if r["change"] == "regressed" else "finding.resolved"
        event_id = _event_id(name, scan_id, r["fingerprint"])
        finding_id = r["finding_id"] or r["prev_finding_id"]
        payload = _base(ctx, name, event_id, occurred_at)
        payload["scan"] = {
            "id": scan_id,
            "previous_scan_id": r["prev_scan_id"],
            "finished_at": audit.format_at(r["scan_finished_at"]),
        }
        payload["finding"] = {
            "id": finding_id,
            "rule_id": r["rule_id"],
            "paragraph": r["paragraph"],
            "status": r["status"],
            "previous_status": r["prev_status"],
            "fingerprint": r["fingerprint"],
            "detail": r["detail"],
            "target": r["target"],
            "location": r["location"],
            # Rule 5: the scanner's own pinpoint references, unchanged.
            "basis": [
                {"pinpoint": b.get("pinpoint"), "source": b.get("source"), "url": b.get("url")}
                for b in (r["basis"] or {}).get("basis", [])
            ],
        }
        payload["evidence"] = _evidence_for(ctx["kind"], r["target"], artifacts)
        payload["link"] = f"{base_url}/findings/{finding_id}"
        events.append(Event(name, event_id, "finding", finding_id, payload))
    return events


def queue_events(session: Session, scan_id: int, *, clock: Clock, base_url: str) -> list[Event]:
    """Audit and queue this scan's events. Runs inside the caller's transaction."""
    now = clock()
    events = events_for_scan(session, scan_id, base_url=base_url, occurred_at=now)
    if not events:
        return []
    hooks = list(session.scalars(select(Webhook).where(Webhook.active).order_by(Webhook.id)))
    for ev in events:
        finding = ev.payload.get("finding", {})
        audit.append(
            session,
            ACTOR,
            "event.emitted",
            ev.entity,
            ev.entity_id,
            {
                "event": ev.name,
                "event_id": ev.event_id,
                "scan_id": scan_id,
                "rule_id": finding.get("rule_id"),
                "fingerprint": finding.get("fingerprint"),
                "previous_status": finding.get("previous_status"),
                "status": finding.get("status"),
            },
            clock=clock,
        )
        for hook in hooks:
            if hook.events and ev.name not in hook.events:
                continue
            session.add(
                Delivery(
                    webhook_id=hook.id,
                    event=ev.name,
                    event_id=ev.event_id,
                    payload=ev.payload,
                    attempt=1,
                    next_attempt_at=now,
                )
            )
    session.flush()
    return events


# --- delivering ----------------------------------------------------------------------


def http_send(url: str, body: bytes, headers: dict[str, str]) -> tuple[int | None, str | None]:
    request = urllib.request.Request(url, data=body, headers=headers, method="POST")  # noqa: S310
    try:
        with urllib.request.urlopen(request, timeout=SEND_TIMEOUT_SECONDS) as resp:  # noqa: S310
            return resp.status, None
    except urllib.error.HTTPError as exc:
        detail = exc.read(300).decode("utf-8", "replace") if exc.fp else ""
        return exc.code, f"HTTP {exc.code}: {detail}".strip()
    except (urllib.error.URLError, OSError, ValueError) as exc:
        return None, f"{type(exc).__name__}: {getattr(exc, 'reason', exc)}"


def deliver_due(
    session_factory: sessionmaker[Session],
    *,
    clock: Clock,
    send: Sender = http_send,
    limit: int = 50,
) -> int:
    """Attempt every due delivery, one claimed row per transaction. Returns attempts made."""
    attempts = 0
    while attempts < limit:
        with session_factory() as session, session.begin():
            now = clock()
            row = session.scalars(
                select(Delivery)
                .where(Delivery.attempted_at.is_(None), Delivery.next_attempt_at <= now)
                .order_by(Delivery.next_attempt_at, Delivery.id)
                .limit(1)
                .with_for_update(skip_locked=True)
            ).first()
            if row is None:
                return attempts
            hook = session.get(Webhook, row.webhook_id)
            assert hook is not None
            row.attempted_at = now
            if not hook.active:
                row.error = "webhook disabled; not sent"
                attempts += 1
                continue
            body = canonical_body(row.payload)
            headers = {
                "Content-Type": "application/json",
                "User-Agent": f"ai-act-evidence-room/{__version__}",
                SIGNATURE_HEADER: sign(hook.secret, int(now.timestamp()), body),
                "X-Evidence-Event": row.event,
                "X-Evidence-Event-Id": row.event_id,
                "X-Evidence-Attempt": str(row.attempt),
            }
            status, error = send(hook.url, body, headers)
            row.status_code = status
            attempts += 1
            if status is not None and 200 <= status < 300:
                row.delivered_at = now
                continue
            row.error = error or f"HTTP {status}"
            if row.attempt < MAX_ATTEMPTS:
                session.add(
                    Delivery(
                        webhook_id=row.webhook_id,
                        event=row.event,
                        event_id=row.event_id,
                        payload=row.payload,
                        attempt=row.attempt + 1,
                        next_attempt_at=now + RETRY_DELAYS[row.attempt - 1],
                    )
                )
            else:
                log.warning(
                    "giving up on %s for webhook %s after %s attempts: %s",
                    row.event_id,
                    row.webhook_id,
                    row.attempt,
                    row.error,
                )
    return attempts


# --- email digest --------------------------------------------------------------------


def digest_message(settings: Settings, scan_id: int, events: Iterable[Event]) -> EmailMessage:
    events = list(events)
    first = events[0].payload
    matter = first["matter"]
    lines = [
        f"Client: {matter['client']}",
        f"Matter: {matter['title']}",
        f"Touchpoint: {first['touchpoint']['target']} ({first['touchpoint']['kind']})",
        f"Scan: {scan_id}",
        "",
    ]
    for ev in events:
        p = ev.payload
        if ev.name == "scan.failed":
            lines.append(f"SCAN FAILED  {p['scan']['error']}")
        else:
            f = p["finding"]
            word = "REGRESSED" if ev.name == "finding.regressed" else "RESOLVED "
            lines.append(
                f"{word}  {f['rule_id']}  Art. {f['paragraph']}  "
                f"{f['previous_status']} -> {f['status']}  {f['target']}"
            )
            lines.append(f"           evidence sha256 {p['evidence']['sha256']}")
        lines.append(f"           {p['link']}")
    lines += ["", SCOPE_LINE]

    msg = EmailMessage()
    msg["Subject"] = (
        f"[evidence-room] {matter['client']} / {matter['title']}: "
        f"{len(events)} change(s) in scan {scan_id}"
    )
    msg["From"] = settings.digest_from
    msg["To"] = ", ".join(settings.digest_to)
    msg.set_content("\n".join(lines))
    return msg


def send_digest(
    settings: Settings,
    scan_id: int,
    events: list[Event],
    *,
    smtp_factory: Callable[..., smtplib.SMTP] = smtplib.SMTP,
) -> bool:
    """Email one digest for a scan's events. Returns False when email is off or none."""
    if not settings.email_enabled or not events:
        return False
    msg = digest_message(settings, scan_id, events)
    with smtp_factory(settings.smtp_host, settings.smtp_port, timeout=SEND_TIMEOUT_SECONDS) as s:
        if settings.smtp_starttls:
            s.starttls()
        if settings.smtp_user:
            s.login(settings.smtp_user, settings.smtp_password)
        s.send_message(msg)
    return True
